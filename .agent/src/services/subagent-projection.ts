import fsp from 'node:fs/promises';
import path from 'node:path';
import { splitSubagentDocument } from '../subagents';

/**
 * Codex subagent projection.
 *
 * Codex reads custom agents as standalone TOML files under `.codex/agents/` — required keys
 * `name`, `description`, `developer_instructions`. It never reads Markdown agents, so a
 * `.codex/agents` directory full of `.md` files looks configured while exposing nothing. The
 * manager therefore generates TOML from the same canonical source (`.agent/agents/*.md`)
 * instead of symlinking, and marks what it generated so repair can never delete a hand-written
 * agent.
 *
 * Read-only declarations have no Codex equivalent (`disallowedTools` does not exist there), so
 * they are translated into one explicit instruction line rather than a `sandbox_mode` that would
 * silently block the test runs a judge needs. Enforcement stays the harness's business and is
 * reported in `harness doctor`, never faked.
 */

export const CODEX_AGENTS_DIR = '.codex/agents';

/** First line of every generated file; the only files repair is allowed to delete. */
export const CODEX_PROJECTION_MARKER = '# generated by harness from .agent/agents/';

/** Instruction line injected when the canonical agent denies the write tools. */
export const READ_ONLY_INSTRUCTION =
  'YOU HAVE NO WRITE PERMISSION. Never create, edit, or delete files, never run git, never delegate further. Report findings only.';

export type CodexProjectionState = 'current' | 'missing' | 'stale' | 'blocked';

export interface CodexProjectionResult {
  state: CodexProjectionState;
  path: string;
  /** Number of generated agent files that are current on disk. */
  agents: number;
  issues: string[];
  /** True only when a sync actually wrote, rewrote, or removed a file. */
  changed: boolean;
}

/** Escapes a value for a single-line TOML basic string. */
function tomlBasicString(value: string): string {
  return JSON.stringify(value.replace(/\r\n/g, '\n'));
}

/**
 * Emits a TOML multi-line string, preferring a literal string so Markdown backslashes and quotes
 * survive untouched. Falls back to an escaped basic string only when the body itself contains
 * `'''`.
 */
function tomlMultiline(value: string): string {
  const body = value.replace(/\r\n/g, '\n').replace(/\s+$/, '');
  if (!body.includes("'''")) return `'''\n${body}\n'''`;
  return `"""\n${body.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"')}\n"""`;
}

/** Normalizes a frontmatter list that may be an array or a comma-separated string. */
function asList(value: unknown): string[] {
  if (Array.isArray(value)) return value.map(v => String(v).trim()).filter(Boolean);
  if (typeof value === 'string') {
    return value.replace(/^\[|\]$/g, '').split(',').map(v => v.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
  }
  return [];
}

/** Maps a canonical `.md` agent file name to the generated `.toml` file name. */
export function codexAgentFileName(markdownFileName: string): string {
  return `${path.basename(markdownFileName, path.extname(markdownFileName))}.toml`;
}

/**
 * Renders one canonical agent as a Codex custom-agent TOML document.
 *
 * @param markdownFileName Canonical `.md` file name, used for the owner marker and fallback id.
 * @param content Raw Markdown of the canonical definition.
 * @returns TOML document, marked as generated.
 */
export function buildCodexAgentToml(markdownFileName: string, content: string): string {
  const { attrs, body } = splitSubagentDocument(content);
  const name = typeof attrs.name === 'string' && attrs.name !== ''
    ? attrs.name
    : path.basename(markdownFileName, path.extname(markdownFileName));
  const description = typeof attrs.description === 'string' ? attrs.description : '';

  const denied = asList(attrs.disallowedTools).map(tool => tool.toLowerCase());
  const deniesWrites = denied.includes('edit') || denied.includes('write');
  const instructions = deniesWrites
    ? `${READ_ONLY_INSTRUCTION}\n\n${body.trim()}`
    : body.trim();

  return [
    `${CODEX_PROJECTION_MARKER}${markdownFileName} — do not edit`,
    `name = ${tomlBasicString(name)}`,
    `description = ${tomlBasicString(description)}`,
    `developer_instructions = ${tomlMultiline(instructions)}`,
    ''
  ].join('\n');
}

/** Reads every canonical agent, keyed by Markdown file name. */
async function readCanonicalAgents(root: string): Promise<Map<string, string>> {
  const dir = path.join(root, '.agent', 'agents');
  const agents = new Map<string, string>();
  let entries: string[];
  try {
    entries = await fsp.readdir(dir);
  } catch {
    return agents;
  }
  for (const entry of entries.sort()) {
    if (!entry.endsWith('.md')) continue;
    try {
      agents.set(entry, await fsp.readFile(path.join(dir, entry), 'utf-8'));
    } catch {
      continue;
    }
  }
  return agents;
}

async function lstatOrNull(target: string) {
  return fsp.lstat(target).catch((err: NodeJS.ErrnoException) => {
    if (err.code === 'ENOENT') return null;
    throw err;
  });
}

/**
 * Computes the projection state without writing anything.
 *
 * @param root Absolute workspace root.
 * @returns State, agent count and the problems a repair would fix.
 */
export async function inspectCodexSubagentProjection(root: string): Promise<CodexProjectionResult> {
  const dir = path.join(path.resolve(root), CODEX_AGENTS_DIR);
  const canonical = await readCanonicalAgents(root);
  const issues: string[] = [];

  const stat = await lstatOrNull(dir);
  if (stat?.isSymbolicLink()) {
    return {
      state: 'blocked',
      path: dir,
      agents: 0,
      changed: false,
      issues: ['`.codex/agents` is a symlink; Codex ignores Markdown agents there. Run `harness heal`.']
    };
  }
  if (canonical.size === 0) {
    return { state: 'current', path: dir, agents: 0, changed: false, issues };
  }
  if (!stat) {
    return { state: 'missing', path: dir, agents: 0, changed: false, issues: ['`.codex/agents` has no generated agents. Run `harness heal`.'] };
  }

  let current = 0;
  const present = new Set((await fsp.readdir(dir)).filter(entry => entry.endsWith('.toml')));
  const owned = new Set([...canonical.keys()].map(codexAgentFileName));
  for (const [file, content] of canonical) {
    const expected = buildCodexAgentToml(file, content);
    const actual = await fsp.readFile(path.join(dir, codexAgentFileName(file)), 'utf-8').catch(() => null);
    if (actual === expected) current += 1;
    else issues.push(`\`.codex/agents/${codexAgentFileName(file)}\` is ${actual === null ? 'missing' : 'stale'}. Run \`harness heal\`.`);
  }
  for (const file of present) {
    if (owned.has(file)) continue;
    const text = await fsp.readFile(path.join(dir, file), 'utf-8').catch(() => '');
    if (text.startsWith(CODEX_PROJECTION_MARKER)) issues.push(`\`.codex/agents/${file}\` is orphaned. Run \`harness heal\`.`);
  }

  return { state: issues.length === 0 ? 'current' : 'stale', path: dir, agents: current, changed: false, issues };
}

/**
 * Regenerates the Codex projection from the canonical agents.
 *
 * Only files carrying {@link CODEX_PROJECTION_MARKER} are rewritten or deleted, so a
 * hand-written Codex agent is preserved and reported instead of being lost.
 *
 * @param root Absolute workspace root.
 * @returns Actions taken, state after the sync, and whether anything was written.
 */
export async function syncCodexSubagentProjection(root: string): Promise<{ actions: string[]; state: CodexProjectionState; changed: boolean }> {
  const dir = path.join(path.resolve(root), CODEX_AGENTS_DIR);
  const canonical = await readCanonicalAgents(root);
  const actions: string[] = [];

  const stat = await lstatOrNull(dir);
  if (stat?.isSymbolicLink()) {
    await fsp.unlink(dir);
    actions.push(`Pruned poisonous ${CODEX_AGENTS_DIR} adapter (Codex reads TOML agents, not Markdown)`);
  }

  if (canonical.size === 0) return { actions, state: 'current', changed: actions.length > 0 };

  await fsp.mkdir(dir, { recursive: true });
  let changed = actions.length > 0;

  const owned = new Set([...canonical.keys()].map(codexAgentFileName));
  for (const [file, content] of canonical) {
    const target = path.join(dir, codexAgentFileName(file));
    const expected = buildCodexAgentToml(file, content);
    const actual = await fsp.readFile(target, 'utf-8').catch(() => null);
    if (actual === expected) continue;
    await fsp.writeFile(target, expected, 'utf-8');
    actions.push(`${actual === null ? 'Generated' : 'Regenerated'} ${CODEX_AGENTS_DIR}/${codexAgentFileName(file)}`);
    changed = true;
  }

  for (const entry of await fsp.readdir(dir)) {
    if (!entry.endsWith('.toml') || owned.has(entry)) continue;
    const target = path.join(dir, entry);
    const text = await fsp.readFile(target, 'utf-8').catch(() => '');
    if (!text.startsWith(CODEX_PROJECTION_MARKER)) {
      actions.push(`Preserved hand-written ${CODEX_AGENTS_DIR}/${entry}`);
      continue;
    }
    await fsp.unlink(target);
    actions.push(`Removed orphaned ${CODEX_AGENTS_DIR}/${entry}`);
    changed = true;
  }

  return { actions, state: 'current', changed };
}
